"""
Расчёт размеров проточной части ПРОТИВОТОЧНОЙ кольцевой камеры сгорания по методике:
Митрофанов В.В. (и др.) «Алгоритм расчёта размеров проточной части камеры сгорания
газотурбинного двигателя гражданской авиации, транспортной машины, судового двигателя»
(books/Mitrofanov.pdf, с. 48…57).

Реализована ветка «Расчёт размеров противоточной камеры сгорания» (с. 56…57), которая
переиспользует часть пунктов из расчёта ПРЯМОТОЧНОЙ камеры (с. 50…53): пп. 12…16 (длина
зоны горения, жаровой трубы, входного «безотрывного» диффузора), пп. 19…21 (число форсунок,
объём зоны горения) и функциональные ограничения п. 24 (без пп. 25…31 — характеристики
запуска, эмиссия, дымность и КПД на режиме «малого газа»: они требуют дополнительных
исходных данных о режиме малого газа и высотно-климатических условиях запуска, не
связанных с геометрией проточной части, и по условию задачи не нужны — «геометрический
облик», без точной оптимизации).

Обозначения и единицы — как в источнике: длины и диаметры в м, площади в м², давления
на входе в формулы Па (переводятся в МПа там, где это дало физически разумный порядок
величины — см. комментарий у sum_mu_f_ozh).

Геометрия входа/выхода КС (D_к,F_к,h_к / D_вых,F_вых,h_вых) в этом проекте берётся не как
независимые исходные данные, а непосредственно из уже выполненных расчётов ЦБК и ТВД
(см. kamera_sgoraniya/main.py) — так КС «подгоняется» под фактические проточные части
компрессора и турбины.
"""
import math

ALPHA_D = 25.0  # центральный угол входного «безотрывного» диффузора КС, град (с.48, задан методикой)

# Параметры варьирования для противоточной КС (с.50): X1=5…6; X2=0,15…0,3; X3=3…3,5; X4=1,2…2
DEFAULTS = dict(X1=5.5, X2=0.2, X3=3.2, X4=1.6)


def sum_mu_f_ozh(G_v, T_k, P_k, X2):
    """
    Суммарная эффективная площадь всех отверстий в жаровой трубе, м² (п.2, с.50).
    G_v, кг/с; T_k, К; P_k — давление за компрессором, МПа.

    В источнике единица P_k явно не указана (типичная для советских методик неоднозначность
    между кгс/см² и СИ). На параметрах данного (малоразмерного) двигателя только МПа даёт
    результат правильного порядка по отношению к функциональному ограничению п.24
    (5 ≤ Fж/ΣμFож ≤ 7) — при кгс/см² или барах это отношение получается на порядок больше.
    """
    return 1.6e-5 * G_v * T_k ** 0.5 / (P_k * (1 - 0.83 * X2 ** 2) ** 2.5 * X2)


def combustor(G_v, P_k, T_k, T_z, alpha, L_o, D_k, F_k, h_k, D_vyh, F_vyh, h_vyh, D_ksn=None, **params):
    """
    Расчёт размеров проточной части противоточной КС.

    G_v — расход воздуха через КС, кг/с (после отбора на нужды ЛА);
    P_k, Па; T_k, К — полное давление и температура за компрессором (вход в КС);
    T_z, К — температура газа перед турбиной (заданная, выход из КС);
    alpha — коэффициент избытка воздуха; L_o — стехиометрический расход воздуха, кг/кг топлива;
    D_k, F_k, h_k — средний диаметр (м), площадь (м²) и высота (м) кольцевого канала на входе
    в КС (= сечение за осевым ЛД компрессора);
    D_vyh, F_vyh, h_vyh — то же на выходе из КС (= сечение на входе в СА турбины);
    D_ksn — наружный диаметр корпуса КС, м. По методике для противоточной КС это заданная
    (а не расчётная) величина — корпус должен вписаться в отведённый габарит. Если не задан,
    подбирается автоматически как минимально достаточный: такой, чтобы внутренний диаметр
    жаровой трубы Джтрвн (п.4) ровно удовлетворял дополнительному ограничению для противоточной
    КС (Джтрвн ≥ Двыхн + 70 мм, с.57) с небольшим запасом — т.е. корпус настолько компактен,
    насколько позволяет геометрия турбины. Получившийся D_ksn сравнивается в отчёте с
    наружным диаметром компрессора (см. kamera_sgoraniya/main.py) — на масштабе малоразмерного
    двигателя КС по этой методике обычно получается заметно шире компрессора.
    """
    p = dict(DEFAULTS)
    unknown = set(params) - set(p)
    if unknown:
        raise KeyError(f"Неизвестные параметры КС: {unknown}")
    p.update(params)
    X1, X2, X3, X4 = p["X1"], p["X2"], p["X3"], p["X4"]

    F_zh = F_vyh * X1  # 1. Площадь жаровой трубы в миделевом сечении
    SmF_ozh = sum_mu_f_ozh(G_v, T_k, P_k / 1e6, X2)  # 2. Суммарная эффективная площадь отверстий
    F_kk = F_k * X4  # 3. Площадь наружного кольцевого канала

    if D_ksn is None:
        D_vyh_n_ = D_vyh + h_vyh / 2
        D_zhtr_vn_min = D_vyh_n_ + 0.07 + 0.010  # доп. ограничение с.57 + запас 10 мм
        D_ksn = math.sqrt(D_zhtr_vn_min ** 2 + 4 / math.pi * (F_kk + F_zh))

    res = dict(params=p, G_v=G_v, P_k=P_k, T_k=T_k, T_z=T_z, alpha=alpha, L_o=L_o,
               D_k=D_k, F_k=F_k, h_k=h_k, D_vyh=D_vyh, F_vyh=F_vyh, h_vyh=h_vyh, D_ksn=D_ksn)

    # ---------------- Противоточная КС, пп. 1…13 (с.56…57) ----------------
    D_zhtr_vn = math.sqrt(D_ksn ** 2 - 4 / math.pi * (F_kk + F_zh))  # 4. Внутренний диаметр жаровой трубы
    D_zhtr_n = math.sqrt(D_zhtr_vn ** 2 + 4 / math.pi * F_zh)  # 5. Наружный диаметр жаровой трубы
    D_zhtr_sr = (D_zhtr_n + D_zhtr_vn) / 2  # 6. Средний диаметр жаровой трубы
    h_zh = (D_zhtr_n - D_zhtr_vn) / 2  # 7. Высота жаровой трубы
    h_sr = (h_zh + h_vyh) / 2  # 8. Средняя высота между миделевым и выходным сечением
    R_g_sr = (D_zhtr_sr - D_vyh) / 4  # 9. Средний радиус газосборника (разворота потока на 180°)
    l_gs = math.pi * R_g_sr  # 10. Длина газосборника (дуга разворота)
    l_gs_rel = l_gs / h_sr  # 11. Относительная длина газосборника
    R_g_n = (D_zhtr_n - D_vyh) / 4  # 12. Наружный радиус газосборника
    R_g_vn = (D_zhtr_vn - D_vyh) / 4  # 13. Внутренний радиус газосборника

    # ---------------- Общие пункты из расчёта прямоточной КС (с.51…52) ----------------
    l_zg = 0.8 * h_zh  # п.12 прямоточной: длина зоны горения
    l_zh = l_zg + l_gs  # п.13: длина жаровой трубы
    n_d1 = 5 * ALPHA_D ** (-0.38)  # п.14: степень расширения малого «безотрывного» диффузора
    h_d1 = n_d1 * h_k  # п.15: высота канала на выходе из малого диффузора
    l_d1 = (h_d1 - h_k) / 2 / math.tan(math.radians(ALPHA_D / 2))  # п.16: длина малого диффузора
    N_f = round(300 * F_zh)  # п.19: число форсунок (3·100·Fж)
    N_f_zap = round(150 * F_zh)  # п.20: число форсунок, подключаемых на запуске
    V_zg = F_zh * l_zg  # п.21: объём зоны горения

    # ---------------- Собственные пп.22…23 противоточной КС (с.57) ----------------
    V_zh = 0.6 * F_zh * l_zh  # объём жаровой трубы
    S_zh = math.pi * (D_zhtr_n + D_zhtr_vn) * l_zh  # площадь боковой поверхности жаровой трубы

    res.update(F_zh=F_zh, SmF_ozh=SmF_ozh, F_kk=F_kk, D_zhtr_vn=D_zhtr_vn, D_zhtr_n=D_zhtr_n,
               D_zhtr_sr=D_zhtr_sr, h_zh=h_zh, h_sr=h_sr, R_g_sr=R_g_sr, l_gs=l_gs, l_gs_rel=l_gs_rel,
               R_g_n=R_g_n, R_g_vn=R_g_vn, l_zg=l_zg, l_zh=l_zh, n_d1=n_d1, h_d1=h_d1, l_d1=l_d1,
               N_f=N_f, N_f_zap=N_f_zap, V_zg=V_zg, V_zh=V_zh, S_zh=S_zh)

    # Собственная геометрическая оценка (не из методики): осевая длина корпуса КС.
    # Источник даёт L_кс только для прямоточной КС (сумма отрезков по прямой); для противоточной
    # явной формулы в тексте нет — жаровая труба развёрнута на 180°, и её длина по средней линии
    # (l_ж) значительно больше осевого габарита корпуса. Оцениваем осевой габарит по цепочке
    # размеров на рис.18: Δ (зазор до форсунок) + l_д1 (малый диффузор) + осевая проекция
    # зоны горения (≈ l_зг) + осевая глубина разворота потока на 180° (≈ 2·R_г_н по наружной
    # линии тока разворота).
    Delta = 2.5 * h_k  # п.17 прямоточной КС: Δ = (2…3)·h_к
    L_ks = Delta + l_d1 + l_zg + 2 * R_g_n
    res.update(Delta=Delta, L_ks=L_ks)

    res["warnings"] = _checks(res)
    return res


def _checks(r):
    """Функциональные ограничения п.24 (с.53) + дополнение для противоточной КС (с.57)."""
    w = []
    ratio1 = r["F_zh"] / r["SmF_ozh"]
    if not 5 <= ratio1 <= 7:
        w.append(f"Fж/ΣμFож = {ratio1:.2f} вне 5…7 (п.24) — на масштабе этого двигателя точное "
                 f"попадание эмпирической формулы не гарантировано, см. X2")
    ratio2 = r["F_kk"] / r["SmF_ozh"]
    if ratio2 < 1.9:
        w.append(f"Fкк/ΣμFож = {ratio2:.2f} < 1,9 (п.24)")
    ratio3 = r["S_zh"] / r["V_zh"]
    if ratio3 > 85:
        w.append(f"Sж/Vж = {ratio3:.1f} м⁻¹ > 85 м⁻¹ (п.24)")
    t_f = math.pi * r["D_zhtr_sr"] / (r["N_f"] * r["h_zh"])
    if t_f > 1:
        w.append(f"t̄ф = {t_f:.2f} > 1 (п.24) — увеличьте число форсунок N_ф")
    dP_f = 3.97e5 * (r["G_v"] / (r["alpha"] * r["L_o"] * r["N_f"])) ** 2
    if dP_f < 0.2e6:
        w.append(f"(ΔPф)расч = {dP_f / 1e6:.3f} МПа < 0,2 МПа (п.24) — уменьшите N_ф")
    T_w = r["T_k"] + 30.6 / (1 + 0.8 * r["alpha"] * r["L_o"]) * (
        -0.11 * ratio3 ** 2 + 19.3 * ratio3)
    if T_w > 1373:
        w.append(f"Tw = {T_w:.0f} К > 1373 К (п.24) — стенка жаровой трубы перегрета")
    D_vyh_n = r["D_vyh"] + r["h_vyh"] / 2
    if r["D_zhtr_vn"] < D_vyh_n + 0.07:
        w.append(f"Джтрвн = {r['D_zhtr_vn'] * 1000:.1f} мм < Двыхн + 70 мм = "
                 f"{(D_vyh_n + 0.07) * 1000:.1f} мм (доп. ограничение для противоточной КС, с.57)")
    r["ratio1"], r["ratio2"], r["ratio3"], r["t_f"], r["dP_f"], r["T_w"] = (
        ratio1, ratio2, ratio3, t_f, dP_f, T_w)
    return w


def print_report(r):
    p = r["params"]
    print("=" * 84)
    print("   РАСЧЁТ ПРОТИВОТОЧНОЙ КОЛЬЦЕВОЙ КАМЕРЫ СГОРАНИЯ (Митрофанов, с.48…57)")
    print("=" * 84)
    print(f"Исходные данные: G_в = {r['G_v']:.3f} кг/с, Pк* = {r['P_k'] / 1000:.1f} кПа, "
          f"Tк* = {r['T_k']:.1f} К, Tz* = {r['T_z']:.1f} К, α = {r['alpha']:.2f}, L0 = {r['L_o']:.2f}")
    print(f"Вход в КС (= выход осевого ЛД ЦБК):  D_к = {r['D_k'] * 1000:.1f} мм, "
          f"F_к = {r['F_k'] * 1e4:.1f} см², h_к = {r['h_k'] * 1000:.2f} мм")
    print(f"Выход из КС (= вход в СА ТВД):        D_вых = {r['D_vyh'] * 1000:.1f} мм, "
          f"F_вых = {r['F_vyh'] * 1e4:.1f} см², h_вых = {r['h_vyh'] * 1000:.2f} мм")
    print(f"Наружный диаметр корпуса КС D_ксн = {r['D_ksn'] * 1000:.1f} мм (принят по габариту ЦБК)")
    print(f"Параметры варьирования: X1={p['X1']}, X2={p['X2']}, X3={p['X3']}, X4={p['X4']}")

    print("\n─── Жаровая труба ───")
    print(f"  Fж = {r['F_zh'] * 1e4:.1f} см², ΣμFож = {r['SmF_ozh'] * 1e4:.2f} см², "
          f"Fкк (наружный канал) = {r['F_kk'] * 1e4:.1f} см²")
    print(f"  Джтрн = {r['D_zhtr_n'] * 1000:.1f} мм, Джтрвн = {r['D_zhtr_vn'] * 1000:.1f} мм, "
          f"Джтрср = {r['D_zhtr_sr'] * 1000:.1f} мм, hж = {r['h_zh'] * 1000:.1f} мм")
    print(f"  hср = {r['h_sr'] * 1000:.1f} мм")

    print("\n─── Газосборник (разворот потока на 180°) ───")
    print(f"  Rгср = {r['R_g_sr'] * 1000:.1f} мм, Rгн = {r['R_g_n'] * 1000:.1f} мм, "
          f"Rгвн = {r['R_g_vn'] * 1000:.1f} мм")
    print(f"  lгс (дуга) = {r['l_gs'] * 1000:.1f} мм, lгс/hср = {r['l_gs_rel']:.2f}")

    print("\n─── Зона горения и жаровая труба в целом ───")
    print(f"  lзг = {r['l_zg'] * 1000:.1f} мм, lж = {r['l_zh'] * 1000:.1f} мм")
    print(f"  Vзг = {r['V_zg'] * 1e6:.1f} см³, Vж = {r['V_zh'] * 1e6:.1f} см³, "
          f"Sж = {r['S_zh'] * 1e4:.1f} см²")

    print("\n─── Малый «безотрывный» диффузор и форсунки ───")
    print(f"  nд1 = {r['n_d1']:.3f}, hд1 = {r['h_d1'] * 1000:.1f} мм, lд1 = {r['l_d1'] * 1000:.1f} мм, "
          f"Δ = {r['Delta'] * 1000:.1f} мм")
    print(f"  Число форсунок Nф = {r['N_f']}, на запуске (Nф)зап = {r['N_f_zap']}")

    print(f"\n─── Осевой габарит КС (авторская оценка по рис.18, см. docstring) ───")
    print(f"  Lкс ≈ {r['L_ks'] * 1000:.1f} мм")

    print("\n─── Проверка функциональных ограничений (п.24, +доп. для противоточной КС) ───")
    print(f"  Fж/ΣμFож = {r['ratio1']:.2f} (норма 5…7)")
    print(f"  Fкк/ΣμFож = {r['ratio2']:.2f} (норма ≥1,9)")
    print(f"  Sж/Vж = {r['ratio3']:.1f} м⁻¹ (норма ≤85 м⁻¹)")
    print(f"  t̄ф = {r['t_f']:.2f} (норма ≤1)")
    print(f"  (ΔPф)расч = {r['dP_f'] / 1e6:.3f} МПа (норма ≥0,2 МПа)")
    print(f"  Tw = {r['T_w']:.0f} К (норма ≤1373 К)")
    if r["warnings"]:
        print("\n⚠️ Замечания:")
        for msg in r["warnings"]:
            print("   - " + msg)
    else:
        print("\n✅ Все проверки пройдены")

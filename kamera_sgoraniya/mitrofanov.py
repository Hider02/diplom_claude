"""
Сравнительная проверка КС по методике Митрофанова В.В. «Алгоритм расчёта размеров проточной части камеры
сгорания газотурбинного двигателя гражданской авиации, транспортной машины, судового двигателя»
(books/Mitrofanov.pdf, с. 48…57; противоточная КС — с. 56…57, рис. 18).

Основная методика расчёта КС в проекте — Мингазов (kamera_sgoraniya/mingazov.py). Здесь на полученной по
Мингазову геометрии вычисляются параметры варьирования Митрофанова X1…X4 и его функциональные ограничения
п. 24 (с. 53) и дополнительное ограничение для противоточной КС (с. 57) — чтобы показать, где методики
расходятся.
"""
import math

DZH_GAP = 0.07  # Джтрвн ≥ Двыхн + 0,07 м — доп. ограничение для противоточной КС (с.57)
RANGES = dict(X1=(5.0, 6.0), X2=(0.15, 0.3), X3=(3.0, 3.5), X4=(1.2, 2.0))  # с.50, противоточная КС


def check(r):
    """
    r — результат kamera_sgoraniya/mingazov.py:combustor(). ΣμFож берётся по отверстиям, рассчитанным по
    Мингазову (μ₀·F₀), т.е. сравнивается одна и та же КС.
    Возвращает словарь с X1…X4, отношениями п.24 и списком расхождений.
    """
    g = r["geo"]
    F_zh, F_kk, F_vyh, F_k = r["F_zht"], r["F_kk"], r["F_g"], r["F_k"]
    SmF = r["params"]["mu_o"] * r["F_o"]
    D_n, D_vn = r["D_zh_n"], r["D_zh_vn"]
    h_zh = r["H_zh"]
    h_sr = (h_zh + r["h_t"]) / 2  # п.8
    l_gs = math.pi * ((D_n + D_vn) / 2 - r["D_t_sr"]) / 4  # пп.9…10: π·R_гср
    l_zh = (g["x_dome"] - g["x_c"]) + l_gs  # п.13: прямой участок + газосборник
    V_zh = 0.6 * F_zh * l_zh  # п.22 (с.57)
    S_zh = math.pi * (D_n + D_vn) * l_zh  # п.23 (с.57)
    N_f = r["n_forc"]
    res = dict(X1=F_zh / F_vyh, X3=l_gs / h_sr, X4=F_kk / F_k, SmF=SmF, l_gs=l_gs, l_zh=l_zh,
               ratio1=F_zh / SmF, ratio2=F_kk / SmF, ratio3=S_zh / V_zh,
               t_f=math.pi * (D_n + D_vn) / 2 / (N_f * h_zh),
               # расход топлива на форсунку — в г/с (результат — Па): в кг/с формула даёт единицы паскалей
               dP_f=3.97e5 * (1000 * r["G_k"] / (r["alpha"] * r["L_o"] * N_f)) ** 2,
               dD=D_vn - r["D_t_n"])
    res["T_w"] = r["T_k"] + 30.6 / (1 + 0.8 * r["alpha"] * r["L_o"]) * (
        -0.11 * res["ratio3"] ** 2 + 19.3 * res["ratio3"])
    w = []
    for name in ("X1", "X3", "X4"):
        lo, hi = RANGES[name]
        if not lo <= res[name] <= hi:
            w.append(f"{name} = {res[name]:.2f} вне {lo}…{hi} (с.50)")
    if not 5 <= res["ratio1"] <= 7:
        w.append(f"Fж/ΣμFож = {res['ratio1']:.2f} вне 5…7")
    if res["ratio2"] < 1.9:
        w.append(f"Fкк/ΣμFож = {res['ratio2']:.2f} < 1,9")
    if res["ratio3"] > 85:
        w.append(f"Sж/Vж = {res['ratio3']:.1f} м⁻¹ > 85 м⁻¹")
    if res["t_f"] > 1:
        w.append(f"t̄ф = {res['t_f']:.2f} > 1")
    if res["dP_f"] < 0.2e6:
        w.append(f"(ΔPф)расч = {res['dP_f'] / 1e6:.2f} МПа < 0,2 МПа")
    if res["T_w"] > 1373:
        w.append(f"Tw = {res['T_w']:.0f} К > 1373 К")
    if res["dD"] < DZH_GAP:
        w.append(f"Джтрвн − Двыхн = {res['dD'] * 1000:.1f} мм < 70 мм (с.57)")
    res["warnings"] = w
    return res


def print_check(c):
    print("\n" + "=" * 88)
    print("   СРАВНЕНИЕ С МЕТОДИКОЙ МИТРОФАНОВА (books/Mitrofanov.pdf, с.48…57) на той же геометрии")
    print("=" * 88)
    print(f"  X1 = Fж/Fвых = {c['X1']:.2f} (5…6), X3 = lгс/hср = {c['X3']:.2f} (3…3,5), "
          f"X4 = Fкк/Fк = {c['X4']:.2f} (1,2…2)")
    print(f"  ΣμFож = μ₀·F₀ = {c['SmF'] * 1e4:.1f} см²; lгс = {c['l_gs'] * 1000:.1f} мм, lж = {c['l_zh'] * 1000:.1f} мм")
    print(f"  Fж/ΣμFож = {c['ratio1']:.2f} (5…7), Fкк/ΣμFож = {c['ratio2']:.2f} (≥1,9), "
          f"Sж/Vж = {c['ratio3']:.1f} м⁻¹ (≤85), t̄ф = {c['t_f']:.2f} (≤1)")
    print(f"  (ΔPф)расч = {c['dP_f'] / 1e6:.2f} МПа (≥0,2), Tw = {c['T_w']:.0f} К (≤1373), "
          f"Джтрвн − Двыхн = {c['dD'] * 1000:.1f} мм (≥70)")
    if c["warnings"]:
        print("  Расхождения с Митрофановым: " + "; ".join(c["warnings"]))
    else:
        print("  ✅ Ограничения Митрофанова тоже выполнены")

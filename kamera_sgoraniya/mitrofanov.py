"""
Расчёт размеров проточной части ПРОТИВОТОЧНОЙ кольцевой камеры сгорания по методике:
Митрофанов В.В. (и др.) «Алгоритм расчёта размеров проточной части камеры сгорания
газотурбинного двигателя гражданской авиации, транспортной машины, судового двигателя»
(books/Mitrofanov.pdf, с. 48…57, схема — рис. 18 на с. 49).

Схема (рис.18 и чертёж реального двигателя books/гг.png): радиальный диффузор ЦБК поднимает воздух до
наружного диаметра КС, колено поворачивает его назад, и осевой ЛД ЦБК выходит прямо в НАРУЖНЫЙ
кольцевой канал F_кк (между корпусом D_ксн и наружной стенкой жаровой трубы D_жтрн). По F_кк воздух
идёт назад к фронтовому устройству с форсунками. Газ в жаровой трубе течёт ВПЕРЁД, в газосборнике,
стоящем сразу за задней стенкой радиального диффузора, разворачивается на 180° радиально внутрь и
выходит назад, в СА ТВД, расположенный ПОД жаровой трубой (Джтрвн ≥ Двыхн + 70 мм, с.57).

Реализована ветка «Расчёт размеров противоточной камеры сгорания» (с. 56…57) + пп. 12…16,
19…21 и функциональные ограничения п.24 расчёта прямоточной КС (с. 51…53), на которые
ссылается методика (без пп. 25…33 — режим малого газа, запуск, эмиссия: для них нет исходных
данных, и на геометрию проточной части они не влияют).

Стыковка с узлами — по втулочным и наружным диаметрам:
  - вход: выход осевого ЛД ЦБК D_к.вн, D_к.н → D_к, h_к, F_к; малый диффузор (пп.14…16) выходит на
    корпус КС, т.е. D_ксн = D_к + h_д1 — заданная по методике величина D_ксн определяется компрессором;
  - выход: вход в СА ТВД D_вых.вн = d_са, D_вых.н = D_са → D_вых, h_вых, F_вых; D_вых.н входит в
    ограничение с.57 и задаёт внутренний корпус КС, D_вых.вн и D_вых.н — концы стенок газосборника.
Требуемый D_ксн выполним только при достаточно «высоком» диффузоре ЦБК: D3/D2 подбирается
скриптом kamera_sgoraniya/podbor_diffuzor.py.

Обозначения и единицы — как в источнике: длины и диаметры в м, площади в м².
"""
import math

ALPHA_D = 25.0  # центральный угол входного «безотрывного» диффузора КС, град (с.48, задан методикой)
DZH_GAP = 0.07  # Джтрвн ≥ Двыхн + 0,07 м — доп. ограничение для противоточной КС (с.57)
GAP_WALL = 0.005  # зазор (со стенкой) между задней стенкой радиального диффузора ЦБК и носком газосборника, м

# Параметры варьирования для противоточной КС (с.50): X1=5…6; X2=0,15…0,3; X3=3…3,5; X4=1,2…2.
# X1 — на нижней границе (компактность по диаметру); X2 — из 5 ≤ Fж/ΣμFож ≤ 7; X4 — верхняя граница:
# даёт наибольшую F_кк при данном F_к, что нужно для Fкк/ΣμFож ≥ 1,9 (п.24).
DEFAULTS = dict(X1=5.0, X2=0.17, X3=3.0, X4=2.0)
RANGES = dict(X1=(5.0, 6.0), X2=(0.15, 0.3), X3=(3.0, 3.5), X4=(1.2, 2.0))
X3_RANGE = RANGES["X3"]


def sum_mu_f_ozh(G_v, T_k, P_k, X2):
    """
    Суммарная эффективная площадь всех отверстий в жаровой трубе, м² (п.2, с.56).
    G_v, кг/с; T_k, К; P_k — давление за компрессором, МПа.

    В источнике единица P_k явно не указана. На параметрах данного (малоразмерного) двигателя
    только МПа даёт результат правильного порядка по отношению к функциональному ограничению
    п.24 (5 ≤ Fж/ΣμFож ≤ 7) — при кгс/см² или барах это отношение получается на порядок больше.
    """
    return 1.6e-5 * G_v * T_k ** 0.5 / (P_k * (1 - 0.83 * X2 ** 2) ** 2.5 * X2)


def annulus(D_vn, D_n):
    """Средний диаметр, высота и площадь кольцевого канала по втулочному и наружному диаметрам."""
    return (D_n + D_vn) / 2, (D_n - D_vn) / 2, math.pi / 4 * (D_n ** 2 - D_vn ** 2)


def _liner(D_zhtr_vn, F_zh):
    """пп.5…7 (с.56): наружный, средний диаметры и высота жаровой трубы по её внутреннему диаметру."""
    D_zhtr_n = math.sqrt(D_zhtr_vn ** 2 + 4 / math.pi * F_zh)
    return D_zhtr_n, (D_zhtr_n + D_zhtr_vn) / 2, (D_zhtr_n - D_zhtr_vn) / 2


def _l_gs_rel(D_zhtr_vn, F_zh, D_vyh, h_vyh):
    """пп.8…11 (с.56…57): относительная длина газосборника l_гс/h_ср как функция Джтрвн."""
    _, D_sr, h_zh = _liner(D_zhtr_vn, F_zh)
    return math.pi * (D_sr - D_vyh) / 4 / ((h_zh + h_vyh) / 2)


def required_D_zhtr_vn(F_zh, D_vyh, h_vyh, D_vyh_n, X3):
    """
    Наименьший внутренний диаметр жаровой трубы, при котором одновременно:
      - Джтрвн ≥ Двыхн + 70 мм (с.57) — жаровая труба проходит над корпусом СА ТВД;
      - l_гс/h_ср ≥ X3 (с.50) — газосборник не короче заданной относительной длины.
    l_гс/h_ср монотонно растёт с Джтрвн (растёт Джтрср, падает hж), второе условие решается делением
    отрезка пополам. Возвращает (Джтрвн, какое условие определило размер).
    """
    D_a = D_vyh_n + DZH_GAP
    if _l_gs_rel(D_a, F_zh, D_vyh, h_vyh) >= X3:
        return D_a, "Джтрвн = Двыхн + 70 мм (с.57)"
    lo, hi = D_a, 10 * D_a
    for _ in range(100):
        mid = (lo + hi) / 2
        if _l_gs_rel(mid, F_zh, D_vyh, h_vyh) < X3:
            lo = mid
        else:
            hi = mid
    return hi, f"l_гс/h_ср = X3 = {X3}"


def combustor(G_v, P_k, T_k, T_z, alpha, L_o, D_k_vn, D_k_n, D_vyh_vn, D_vyh_n, diff, **params):
    """
    Расчёт размеров проточной части противоточной КС.

    G_v — расход воздуха через КС, кг/с (после отбора на нужды ЛА);
    P_k, Па; T_k, К — полное давление и температура за компрессором (вход в КС);
    T_z, К — температура газа перед турбиной; alpha — коэффициент избытка воздуха;
    L_o — стехиометрический расход воздуха, кг/кг топлива;
    D_k_vn, D_k_n — втулочный и наружный диаметры на выходе осевого ЛД ЦБК (вход в КС), м;
    D_vyh_vn, D_vyh_n — втулочный и наружный диаметры на входе в СА ТВД (выход из КС), м;
    diff — геометрия диффузора ЦБК для компоновки, м: r3, b3 (выход радиального диффузора),
    Rb (радиус колена), h4 (высота канала за коленом), L_ld (осевая длина ЛД).
    """
    p = dict(DEFAULTS)
    unknown = set(params) - set(p)
    if unknown:
        raise KeyError(f"Неизвестные параметры КС: {unknown}")
    p.update(params)
    X1, X2, X3, X4 = p["X1"], p["X2"], p["X3"], p["X4"]

    D_k, h_k, F_k = annulus(D_k_vn, D_k_n)
    D_vyh, h_vyh, F_vyh = annulus(D_vyh_vn, D_vyh_n)

    # пп.14…16 прямоточной КС: малый «безотрывный» диффузор на выходе ЛД ЦБК; его наружная стенка
    # выходит на корпус КС, поэтому D_ксн (в методике — заданная величина) определяется компрессором
    n_d1 = 5 * ALPHA_D ** (-0.38)  # п.14: степень расширения
    h_d1 = n_d1 * h_k  # п.15: высота канала на выходе
    l_d1 = (h_d1 - h_k) / 2 / math.tan(math.radians(ALPHA_D / 2))  # п.16: длина
    F_k1 = math.pi * D_k * h_d1  # площадь на выходе из малого диффузора (F_к1 на рис.18)
    D_ksn = D_k + h_d1

    F_zh = F_vyh * X1  # 1. Площадь жаровой трубы в миделевом сечении
    SmF_ozh = sum_mu_f_ozh(G_v, T_k, P_k / 1e6, X2)  # 2. Суммарная эффективная площадь отверстий
    F_kk = F_k * X4  # 3. Площадь наружного кольцевого канала

    # ---------------- Противоточная КС, пп. 4…13 (с.56…57) ----------------
    arg = D_ksn ** 2 - 4 / math.pi * (F_kk + F_zh)
    if arg <= 0:
        raise ValueError(f"D_ксн = {D_ksn * 1000:.1f} мм мал: жаровая труба и канал F_кк не помещаются в корпус "
                         f"— поднимите диффузор ЦБК (kamera_sgoraniya/podbor_diffuzor.py)")
    D_zhtr_vn = math.sqrt(arg)  # 4. Внутренний диаметр жаровой трубы
    D_zhtr_n, D_zhtr_sr, h_zh = _liner(D_zhtr_vn, F_zh)  # 5…7. Наружный, средний диаметры, высота
    h_sr = (h_zh + h_vyh) / 2  # 8. Средняя высота между миделевым и выходным сечением
    R_g_sr = (D_zhtr_sr - D_vyh) / 4  # 9. Средний радиус газосборника
    l_gs = math.pi * R_g_sr  # 10. Длина газосборника
    l_gs_rel = l_gs / h_sr  # 11. Относительная длина газосборника
    R_g_n = (D_zhtr_n - D_vyh) / 4  # 12. Наружный радиус газосборника
    R_g_vn = (D_zhtr_vn - D_vyh) / 4  # 13. Внутренний радиус газосборника

    # ---------------- Общие пункты из расчёта прямоточной КС (с.51…52) ----------------
    l_zg = 0.8 * h_zh  # п.12: длина зоны горения
    l_zh = l_zg + l_gs  # п.13: длина жаровой трубы
    N_f = round(300 * F_zh)  # п.19: число форсунок (3·100·Fж)
    N_f_zap = round(150 * F_zh)  # п.20: число форсунок, подключаемых на запуске
    V_zg = F_zh * l_zg  # п.21: объём зоны горения

    # ---------------- Собственные пп.22…23 противоточной КС (с.57) ----------------
    V_zh = 0.6 * F_zh * l_zh  # объём жаровой трубы
    S_zh = math.pi * (D_zhtr_n + D_zhtr_vn) * l_zh  # площадь боковой поверхности жаровой трубы

    D_zhtr_vn_req, req_why = required_D_zhtr_vn(F_zh, D_vyh, h_vyh, D_vyh_n, X3)

    res = dict(params=p, G_v=G_v, P_k=P_k, T_k=T_k, T_z=T_z, alpha=alpha, L_o=L_o,
               D_k_vn=D_k_vn, D_k_n=D_k_n, D_k=D_k, F_k=F_k, h_k=h_k,
               D_vyh_vn=D_vyh_vn, D_vyh_n=D_vyh_n, D_vyh=D_vyh, F_vyh=F_vyh, h_vyh=h_vyh,
               n_d1=n_d1, h_d1=h_d1, l_d1=l_d1, F_k1=F_k1, D_ksn=D_ksn,
               F_zh=F_zh, SmF_ozh=SmF_ozh, F_kk=F_kk, D_zhtr_vn=D_zhtr_vn, D_zhtr_n=D_zhtr_n,
               D_zhtr_sr=D_zhtr_sr, h_zh=h_zh, h_sr=h_sr, R_g_sr=R_g_sr, l_gs=l_gs, l_gs_rel=l_gs_rel,
               R_g_n=R_g_n, R_g_vn=R_g_vn, l_zg=l_zg, l_zh=l_zh, N_f=N_f, N_f_zap=N_f_zap, V_zg=V_zg,
               V_zh=V_zh, S_zh=S_zh, Delta=2.5 * h_k,  # п.17: Δ = (2…3)·h_к — зазор до торцов форсунок
               D_zhtr_vn_req=D_zhtr_vn_req, req_why=req_why)
    res["geo"] = layout(res, diff)
    res["warnings"] = _checks(res)
    return res


def diffuser_hub(diff, n=40):
    """
    Втулочная (внутренняя по повороту) стенка диффузора ЦБК от задней стенки радиального диффузора
    через колено до выхода ЛД — в координатах КС (x = 0 — выход ЛД, м). Колено — как в
    kompressor/plot.py: средняя линия — дуга радиуса Rb, ширина канала линейно b3 → h4.
    """
    r3, b3, Rb, h4, L_ld = diff["r3"], diff["b3"], diff["Rb"], diff["h4"], diff["L_ld"]
    x_cc = -L_ld - Rb  # ось радиального диффузора
    pts = []
    for j in range(n + 1):
        phi = j / n * math.pi / 2
        b = b3 + (h4 - b3) * phi / (math.pi / 2)
        cx, cr = x_cc + Rb * (1 - math.cos(phi)), r3 + Rb * math.sin(phi)
        pts.append((cx + b / 2 * math.cos(phi), cr - b / 2 * math.sin(phi)))
    return x_cc + b3 / 2, pts  # задняя стенка радиального диффузора, контур колена (+ далее ЛД при r = r4 − h4/2)


def layout(r, diff):
    """
    Меридиональный контур КС, м. Ось x — вдоль оси двигателя назад (от компрессора к турбине),
    x = 0 — выход осевого ЛД ЦБК; радиусы — от оси двигателя.

    Методика задаёт диаметры и площади, но не полный контур; принятые построения (по рис.18 и books/гг.png):
      1) малый диффузор (пп.14…16) — продолжение канала ЛД ЦБК, стенки расходятся симметрично на α_д/2;
         наружная стенка переходит в корпус КС D_ксн;
      2) газосборник стоит вплотную (GAP_WALL) за задней стенкой радиального диффузора ЦБК; он образован
         двумя полуокружностями: наружная стенка соединяет Джтрн с втулкой СА (D_вых.вн), внутренняя —
         Джтрвн с корпусом СА (D_вых.н), обе заканчиваются в плоскости входа в СА ТВД. Их радиусы
         (D_жтрн − D_вых.вн)/4 и (D_жтрвн − D_вых.н)/4 — «стеночные» аналоги пп.12…13, которые в
         методике отнесены к D_вых (среднему): по среднему диаметру стенки не попали бы на реальные
         втулку и корпус СА;
      3) жаровая труба: прямой участок l_зг от газосборника до купола-полуокружности (h_ж/2);
         за куполом — зазор Δ до заднего торца корпуса (торцы форсунок, п.17);
      4) внутренний корпус КС — на диаметре корпуса СА D_вых.н (под жаровой трубой — внутренняя
         воздушная полость, над ТВД).
    """
    R = lambda D: D / 2
    r_k_vn, r_k_n, r_k = R(r["D_k_vn"]), R(r["D_k_n"]), R(r["D_k"])
    r_vyh_vn, r_vyh_n = R(r["D_vyh_vn"]), R(r["D_vyh_n"])
    r_zh_vn, r_zh_n, r_ksn = R(r["D_zhtr_vn"]), R(r["D_zhtr_n"]), R(r["D_ksn"])

    x_back, hub = diffuser_hub(diff)
    rc_o, Ro = (r_zh_n + r_vyh_vn) / 2, (r_zh_n - r_vyh_vn) / 2
    rc_i, Ri = (r_zh_vn + r_vyh_n) / 2, (r_zh_vn - r_vyh_n) / 2
    x_nose = x_back + GAP_WALL
    x_c = x_nose + Ro  # начало прямого участка жаровой трубы = вход в СА ТВД
    x_dome = x_c + r["l_zg"]
    x_end = x_dome + r["h_zh"] / 2 + r["Delta"]

    # Наименьший радиальный зазор между стенкой диффузора ЦБК (колено + ЛД + малый диффузор) и наружной
    # стенкой газосборника / жаровой трубы — они не должны пересекаться
    wall = hub + [(0.0, r_k_vn), (r["l_d1"], r_k - r["h_d1"] / 2)]
    clear = math.inf
    for (xa, ra), (xb, rb) in zip(wall, wall[1:]):
        for s in (0.0, 0.5, 1.0):
            x, rw = xa + (xb - xa) * s, ra + (rb - ra) * s
            if x >= x_c:
                r_out = r_zh_n
            elif x > x_c - Ro:
                r_out = rc_o + math.sqrt(Ro ** 2 - (x - x_c) ** 2)
            else:
                continue
            clear = min(clear, rw - r_out)

    return dict(r_k_vn=r_k_vn, r_k_n=r_k_n, r_d1_vn=r_k - r["h_d1"] / 2, r_d1_n=r_k + r["h_d1"] / 2,
                x_d1=r["l_d1"], x_back=x_back, hub=hub, r3=diff["r3"], x_nose=x_nose,
                rc_o=rc_o, Ro=Ro, rc_i=rc_i, Ri=Ri, x_c=x_c, x_dome=x_dome, x_end=x_end, L_ks=x_end,
                L_under=x_end - x_c, clear=clear,
                r_vyh_vn=r_vyh_vn, r_vyh_n=r_vyh_n, r_zh_vn=r_zh_vn, r_zh_n=r_zh_n, r_ksn=r_ksn)


def _checks(r):
    """Функциональные ограничения п.24 (с.53) + дополнение для противоточной КС (с.57)
    + проверки стыковки с ЦБК."""
    w = []
    g = r["geo"]
    ratio1 = r["F_zh"] / r["SmF_ozh"]
    if not 5 <= ratio1 <= 7:
        w.append(f"Fж/ΣμFож = {ratio1:.2f} вне 5…7 (п.24) — подберите X2")
    ratio2 = r["F_kk"] / r["SmF_ozh"]
    if ratio2 < 1.9:
        w.append(f"Fкк/ΣμFож = {ratio2:.2f} < 1,9 (п.24) — мала площадь F_к на выходе ЦБК")
    ratio3 = r["S_zh"] / r["V_zh"]
    if ratio3 > 85:
        w.append(f"Sж/Vж = {ratio3:.1f} м⁻¹ > 85 м⁻¹ (п.24)")
    t_f = math.pi * r["D_zhtr_sr"] / (r["N_f"] * r["h_zh"])
    if t_f > 1:
        w.append(f"t̄ф = {t_f:.2f} > 1 (п.24) — увеличьте число форсунок N_ф")
    # Расход топлива на форсунку подставляется в г/с (результат — Па): в кг/с формула даёт единицы
    # паскалей, что физически бессмысленно; в г/с — порядок МПа, типичный для центробежных форсунок.
    dP_f = 3.97e5 * (1000 * r["G_v"] / (r["alpha"] * r["L_o"] * r["N_f"])) ** 2
    if dP_f < 0.2e6:
        w.append(f"(ΔPф)расч = {dP_f / 1e6:.3f} МПа < 0,2 МПа (п.24) — уменьшите N_ф")
    T_w = r["T_k"] + 30.6 / (1 + 0.8 * r["alpha"] * r["L_o"]) * (-0.11 * ratio3 ** 2 + 19.3 * ratio3)
    if T_w > 1373:
        w.append(f"Tw = {T_w:.0f} К > 1373 К (п.24) — стенка жаровой трубы перегрета")
    if r["D_zhtr_vn"] < r["D_vyh_n"] + DZH_GAP - 1e-9:
        w.append(f"Джтрвн = {r['D_zhtr_vn'] * 1000:.1f} мм < Двыхн + 70 мм = "
                 f"{(r['D_vyh_n'] + DZH_GAP) * 1000:.1f} мм (с.57) — поднимите диффузор ЦБК "
                 f"(kamera_sgoraniya/podbor_diffuzor.py)")
    lo, hi = X3_RANGE
    if not lo - 1e-3 <= r["l_gs_rel"] <= hi + 1e-3:
        w.append(f"l_гс/h_ср = {r['l_gs_rel']:.2f} вне X3 = {lo}…{hi} (с.50) — "
                 + ("поднимите" if r["l_gs_rel"] < lo else "опустите") + " диффузор ЦБК")
    for name, (lo, hi) in RANGES.items():
        if not lo <= r["params"][name] <= hi:
            w.append(f"{name} = {r['params'][name]} вне рекомендованного диапазона {lo}…{hi} (с.50)")
    if g["clear"] < 0:
        w.append(f"Газосборник/жаровая труба пересекают стенку диффузора ЦБК (зазор {g['clear'] * 1000:.1f} мм)")
    r["ratio1"], r["ratio2"], r["ratio3"], r["t_f"], r["dP_f"], r["T_w"] = (
        ratio1, ratio2, ratio3, t_f, dP_f, T_w)
    return w



"""
Расчёт облика петлевой (противоточной) камеры сгорания по методике:
Мингазов Б.Г. и др., гл. 8 «Расчёт облика камеры сгорания на основе газодинамических расчётов её
проточной части и статистических данных прототипов» (books/Мингазов.pdf, с. 225…244), п. 8.10 —
«Расчёт петлевой камеры сгорания» (рис. 8.3), остальное — по общей схеме пп. 8.1…8.8.

Схема (рис. 8.3 и чертёж реального двигателя books/гг.png): радиальный диффузор ЦБК поднимает воздух до
наружного диаметра КС, осевой ЛД ЦБК выходит в диффузор КС (п. 8.3) и через внезапное расширение — в
наружный кольцевой канал над жаровой трубой. Газ в ЖТ течёт вперёд, в газосборнике (он же смеситель,
п. 8.10) разворачивается на 180° внутрь и выходит в СА ТВД, стоящий под ЖТ.

Стыковка с узлами — по втулочным и наружным диаметрам:
  - вход: выход осевого ЛД ЦБК D_к.вн, D_к.н → F_к, D_к.ср, h_к, W_к (п. 8.2.1…8.2.4);
  - выход: вход в СА ТВД D_т.вн = d_са, D_т.н = D_са → F_г, W_г (п. 8.2.5…8.2.7); стенки газосборника
    приходят на втулку и корпус СА;
  - наружный диаметр КС D_н = D_2н — наружная стенка зоны внезапного расширения диффузора КС
    («наружный диаметр петлевой КС соответствует наружному диаметру ЦБК», п. 8.10).
Высота радиального диффузора ЦБК (D3/D2) подбирается скриптом kamera_sgoraniya/podbor_diffuzor.py так,
чтобы наружная стенка ЖТ (п. 8.10: H_ж = 0,7·H_к, по среднему диаметру) продолжала внутреннюю стенку
зоны внезапного расширения — поток из диффузора КС уходит в наружный канал над ЖТ без поджатия.

Единицы — СИ (м, м², Па, К, кг/с).
"""
import math

R_V = 287.0  # газовая постоянная воздуха, Дж/(кг·К) (п. 8.2.1)
R_G = 288.0  # газовая постоянная продуктов сгорания, Дж/(кг·К)
K_V, K_G = 1.4, 1.33
GAP_WALL = 0.005  # зазор (со стенкой) между задней стенкой радиального диффузора ЦБК и носком газосборника, м
CLEAR_MIN = 0.003  # наименьший зазор между стенкой диффузора ЦБК и ЖТ/газосборником (толщина стенки), м

DEFAULTS = dict(
    eta_g=0.98,  # полнота сгорания (п. 8.1.2)
    H_u=43.0e6,  # низшая теплотворная способность керосина, Дж/кг (п. 8.1.2)
    G_ohl=0.05,  # относительный расход воздуха на охлаждение турбины (п. 8.1.3)
    # Диффузор КС (п. 8.3, рекомендации п. 8.9)
    L_d_rel=2.5,  # L_д/h_к = 1,5…2,5
    alpha_d=12.0,  # угол раскрытия безотрывного участка, град (10…12°)
    k_r=1.2,  # относительная площадь внезапного расширения F2/F1 = 1,15…1,25
    dl_rel=1.75,  # Δl/h_к = 1,5…2,0
    # Проточная часть петлевой КС (п. 8.10)
    dp_q_ks=30.0,  # ΔP_к/q_к для петлевой КС («необходимо увеличить до 30»)
    dp_q_d=10.0,  # ΔP_д/q_к для петлевой КС
    k_opt=0.7,  # F_ж.т/F_m = 0,7…0,8
    H_zh_rel=0.7,  # H_ж/H_к для петлевой КС
    A=0.06, theta=0.3,  # п. 8.4.8: коэффициент для кольцевых КС, неравномерность θ = 0,2…0,4
    # Распределение воздуха (п. 8.5.1, для петлевой КС — п. 8.10). Сумма должна быть 1; при рекомендуемых
    # F̄фр = 0,1…0,2, F̄озг = 0,2…0,3, F̄озс = 0,1…0,2, F̄охл = 0,1…0,2 максимум суммы 0,9, поэтому одна доля
    # выходит за рекомендацию; принято охлаждение 0,3 — как в исходном расчёте в Маткаде (books/ks.xmcd)
    F_fr=0.2, F_ozg=0.3, F_ozs=0.2, F_ohl=0.3,
    L_pz_rel=0.3,  # L_п.з/H_ж.т
    L_sm_rel=1.2,  # L_см/H_ж.т = 1,2…1,5
    # Отверстия (п. 8.6)
    m=0.3,  # относительная глубина проникновения струи 0,2…0,5
    mu_o=0.7,  # коэффициент расхода отверстий
    d_ozs_rel=1.5,  # d_озс/d_озг
    # Пояса охлаждения (п. 8.6.7): рекомендуется 5…7 поясов со щелью h_s = 1…2 мм. При h_s = 1 мм площади
    # F_охл хватает лишь на ~3 пояса, поэтому число поясов принимается не меньше n_ohl_min, а щель
    # уменьшается до h_s = F_охл/(n·π·(D_ж.н + D_ж.вн)); щель не меньше h_s_min — по технологичности
    h_s_max=0.001, n_ohl_min=5, h_s_min=0.0005,
    # Фронтовое устройство (п. 8.7)
    t_fr=0.5,  # относительный шаг фронтовых устройств (0,2…0,5)
    delta_z=0.001, n_z_bl=8, phi_z=60.0,  # толщина и число лопаток завихрителя, угол установки, град
    R_vnz=0.005,  # внутренний радиус завихрителя = радиус корпуса форсунки, м (0,005…0,008)
    beta_NOx=4.6,  # β = EI_CO/EI_CH (п. 8.8.4)
)

RECOMMEND = dict(W_k=(100, 150), W_g=(180, 200), W_m=(15, 30), W_o=(80, 120), W_szht=(25, 35),
                 W_kk=(50, 70), n_ohl=(5, 7), F_fr=(0.1, 0.2), F_ozg=(0.2, 0.3), F_ozs=(0.1, 0.2),
                 F_ohl=(0.1, 0.2), d_ozg=(0.012, 0.016))


def cp_gas(T):
    """Средняя теплоёмкость газа c_pг, Дж/(кг·К): 1,1…1,3 кДж/(кг·К) для T = 1100…1700 К (п. 8.1.2)."""
    return 1100 + 200 * min(max((T - 1100) / 600, 0.0), 1.0)


def _static_W(G, T0, p0, F, k, R):
    """Скорость по уравнению расхода с плотностью по статическим параметрам (п. 8.2.1, 8.2.5):
    ρ = p/(R·T), p = p*·π(λ), T = T*·τ(λ). Возвращает (W, λ, ρ)."""
    a_kr = math.sqrt(2 * k / (k + 1) * R * T0)
    W = G / (p0 / (R * T0) * F)
    for _ in range(100):
        lam = W / a_kr
        tau = 1 - (k - 1) / (k + 1) * lam ** 2
        rho = p0 * tau ** (k / (k - 1)) / (R * T0 * tau)
        W_new = G / (rho * F)
        if abs(W_new - W) < 1e-9:
            break
        W = W_new
    return W, W / a_kr, rho


def diffuser_hub(diff, n=40):
    """
    Втулочная (внутренняя по повороту) стенка диффузора ЦБК от задней стенки радиального диффузора через
    колено до выхода ЛД — в координатах КС (x = 0 — выход ЛД, м). Колено — как в kompressor/plot.py:
    средняя линия — дуга радиуса Rb, ширина канала линейно b3 → h4; ЛД сужается от h4 до h5.
    """
    r3, b3, Rb, h4, L_ld = diff["r3"], diff["b3"], diff["Rb"], diff["h4"], diff["L_ld"]
    x_cc = -L_ld - Rb  # ось радиального диффузора
    pts = []
    for j in range(n + 1):
        phi = j / n * math.pi / 2
        b = b3 + (h4 - b3) * phi / (math.pi / 2)
        cx, cr = x_cc + Rb * (1 - math.cos(phi)), r3 + Rb * math.sin(phi)
        pts.append((cx + b / 2 * math.cos(phi), cr - b / 2 * math.sin(phi)))
    return x_cc + b3 / 2, pts


def combustor(G_k, P_k, T_k, T_g, alpha, L_o, sigma_ks, D_k_vn, D_k_n, D_t_vn, D_t_n, diff, **params):
    """
    Расчёт петлевой КС по Мингазову.

    G_k — расход воздуха через КС, кг/с; P_k, Па; T_k, К — полные давление и температура за компрессором;
    T_g — температура газа перед турбиной, К; alpha — коэффициент избытка воздуха из цикла (по нему расход
    топлива; α по п. 8.1.2 считается для сравнения); L_o — стехиометрический коэффициент; sigma_ks —
    коэффициент восстановления полного давления в КС из цикла (ΔP_к/P_к = 1 − σ_кс в п. 8.4.1);
    D_k_vn, D_k_n — втулочный и наружный диаметры выхода ЛД ЦБК, м; D_t_vn, D_t_n — то же на входе в СА ТВД;
    diff — геометрия диффузора ЦБК для компоновки: r3, b3, Rb, h4, L_ld, м.
    """
    p = dict(DEFAULTS)
    unknown = set(params) - set(p)
    if unknown:
        raise KeyError(f"Неизвестные параметры КС: {unknown}")
    p.update(params)
    r = dict(params=p, G_k=G_k, P_k=P_k, T_k=T_k, T_g=T_g, alpha=alpha, L_o=L_o, sigma_ks=sigma_ks,
             D_k_vn=D_k_vn, D_k_n=D_k_n, D_t_vn=D_t_vn, D_t_n=D_t_n)

    # ---------- 8.1. Исходные данные ----------
    c_pg, c_pv = cp_gas(T_g), 1005.0
    alpha_M = (p["H_u"] * p["eta_g"] - c_pg * T_g) / (L_o * (c_pg * T_g - c_pv * T_k))  # 8.1.2
    G_t = G_k * (1 - p["G_ohl"]) / (alpha * L_o)  # 8.1.3 (α — из цикла)
    r.update(c_pg=c_pg, alpha_M=alpha_M, G_t=G_t)

    # ---------- 8.2. Входные и выходные геометрические параметры ----------
    F_k = math.pi / 4 * (D_k_n ** 2 - D_k_vn ** 2)
    D_k_sr, h_k = (D_k_n + D_k_vn) / 2, (D_k_n - D_k_vn) / 2  # 8.2.3…8.2.4
    W_k, lam_k, rho_k = _static_W(G_k, T_k, P_k, F_k, K_V, R_V)  # 8.2.1 (F_к задана компрессором)
    G_g = G_k + G_t
    P_g = sigma_ks * P_k
    F_g = math.pi / 4 * (D_t_n ** 2 - D_t_vn ** 2)
    W_g, lam_g, rho_g_sa = _static_W(G_g, T_g, P_g, F_g, K_G, R_G)  # 8.2.5 (F_г задана турбиной)
    D_t_sr, h_t = (D_t_n + D_t_vn) / 2, (D_t_n - D_t_vn) / 2  # 8.2.7
    r.update(F_k=F_k, D_k_sr=D_k_sr, h_k=h_k, W_k=W_k, lam_k=lam_k, rho_k=rho_k, d_vt_k=D_k_vn / D_k_n,
             G_g=G_g, P_g=P_g, F_g=F_g, W_g=W_g, lam_g=lam_g, D_t_sr=D_t_sr, h_t=h_t, d_vt_t=D_t_vn / D_t_n)

    # ---------- 8.3. Диффузор КС ----------
    L_d = p["L_d_rel"] * h_k
    n_d = 1 + 0.32 * math.sqrt(p["L_d_rel"]) + 0.005 * p["L_d_rel"]  # 8.3.1
    F1 = F_k * n_d  # 8.3.2
    d_d = D_k_sr + 2 * L_d * math.tan(math.radians(p["alpha_d"] / 2))  # 8.3.3
    h1 = F1 / (math.pi * d_d)  # 8.3.4
    D1_n, D1_vn = d_d + h1, d_d - h1  # 8.3.5
    F2 = p["k_r"] * F1  # 8.3.6
    h2 = F2 / (math.pi * d_d)  # 8.3.7
    D2_n, D2_vn = d_d + h2, d_d - h2  # 8.3.8
    dl = p["dl_rel"] * h_k  # 8.3.9
    dp_q_d_local = 0.30 * 0.45 * (1 - 1 / (1.1 * n_d)) ** 2  # 8.3.10 (по скоростному напору на входе в диффузор)
    r.update(L_d=L_d, n_d=n_d, F1=F1, d_d=d_d, h1=h1, D1_n=D1_n, D1_vn=D1_vn, F2=F2, h2=h2, D2_n=D2_n,
             D2_vn=D2_vn, dl=dl, dp_q_d_local=dp_q_d_local)

    # ---------- 8.10 (8.4). Проточная часть петлевой КС ----------
    dp_P = 1 - sigma_ks
    F_m_loss = math.sqrt(R_G / 2 * (G_k * T_k ** 0.5 / P_k) ** 2 * p["dp_q_ks"] / dp_P)  # 8.4.1 (для сравнения)
    D_n = D2_n  # наружный диаметр КС = наружная стенка зоны внезапного расширения диффузора КС
    H_k = (D_n - D_t_n) / 2  # задан наружный диаметр турбины
    D_sr = (D_n + D_t_n) / 2
    F_m = math.pi * D_sr * H_k
    F_zht = p["k_opt"] * F_m  # 8.4.5
    H_zh = p["H_zh_rel"] * H_k  # для петлевой КС
    D_zh_n, D_zh_vn = D_sr + H_zh, D_sr - H_zh  # 8.4.7
    dp_q_zht = p["dp_q_ks"] - p["dp_q_d"]  # 8.4.8
    L_zht = H_zh / (p["A"] * dp_q_zht * math.log(1 / (1 - p["theta"])))  # 8.4.8
    L_k = L_d + dl + L_zht  # 8.4.9
    F_kk = math.pi / 4 * (D_n ** 2 - D_zh_n ** 2)  # наружный канал над ЖТ
    F_vk = math.pi / 4 * (D_zh_vn ** 2 - D_t_n ** 2)  # внутренняя полость под ЖТ (над СА ТВД)
    r.update(dp_P=dp_P, F_m_loss=F_m_loss, D_n=D_n, H_k=H_k, D_sr=D_sr, F_m=F_m, F_zht=F_zht, H_zh=H_zh,
             D_zh_n=D_zh_n, D_zh_vn=D_zh_vn, dp_q_zht=dp_q_zht, L_zht=L_zht, L_k=L_k, F_kk=F_kk, F_vk=F_vk)

    # ---------- 8.5. Распределение воздуха и скорости («холодный» режим) ----------
    L_pz = p["L_pz_rel"] * H_zh
    L_sm = p["L_sm_rel"] * H_zh  # в петлевой КС смеситель совпадает с поворотом (газосборником)
    L_zd = L_zht - (L_pz + L_sm)
    V = G_k * R_V * T_k / P_k  # объёмный расход по полным параметрам, м³/с
    V_o = V * (1 - p["G_ohl"])
    F_o = F_m / math.sqrt(dp_q_zht)  # 8.5.2
    W_m = V / F_m  # 8.5.3
    W_o = V_o / F_o  # 8.5.4
    W_szht = V_o * p["k_opt"] / F_zht  # 8.5.5
    W_pz = V_o * p["F_fr"] * p["k_opt"] / F_zht  # 8.5.6
    # 8.5.7: в формуле стоит (1 − k_опт)·F_ж.т; по смыслу (площадь каналов между стенками КС и ЖТ) это
    # (1 − k_опт)·F_m — так и принято
    W_kk = V_o * (1 - p["F_fr"]) / ((1 - p["k_opt"]) * F_m)
    W_zg = V_o * (p["F_fr"] + p["F_ozg"]) * p["k_opt"] / F_zht  # 8.6.1
    r.update(L_pz=L_pz, L_sm=L_sm, L_zd=L_zd, V=V, F_o=F_o, W_m=W_m, W_o=W_o, W_szht=W_szht, W_pz=W_pz,
             W_kk=W_kk, W_zg=W_zg, W_kk_fact=V / F_kk)

    # ---------- 8.6. Отверстия в ЖТ ----------
    # q̄ = ρW₀²/(ρ_гW_г²): струя воздуха к сносящему потоку газа в ЖТ; газ — при T_г и средней по ЖТ скорости
    rho_v = P_k / (R_V * T_k)
    rho_gz = P_k / (R_G * T_g)
    W_gz = G_g / (rho_gz * F_zht)
    q = rho_v * W_o ** 2 / (rho_gz * W_gz ** 2)
    F_ozg = F_o * p["F_ozg"]
    d_eff = p["m"] * H_zh / (1.25 * q ** 0.25) * (1 + q * W_zg / W_o * F_ozg / F_zht)  # 8.6.1
    d_ozg = d_eff / math.sqrt(p["mu_o"])  # 8.6.2
    n_ozg = max(2, math.ceil(4 * F_ozg / (math.pi * d_ozg ** 2)))  # 8.6.3
    t_o = math.pi * (D_zh_n + D_zh_vn) / n_ozg  # 8.6.4
    n_ozg_n = round(math.pi * D_zh_n / t_o)
    n_ozg_vn = n_ozg - n_ozg_n
    d_ozs = p["d_ozs_rel"] * d_ozg  # 8.6.5
    F_ozs = F_o * p["F_ozs"]
    n_ozs = max(2, math.ceil(4 * F_ozs / (math.pi * d_ozs ** 2)))
    t_ozs = math.pi * (D_zh_n + D_zh_vn) / n_ozs  # 8.6.6
    n_ozs_n = round(math.pi * D_zh_n / t_ozs)
    n_ozs_vn = n_ozs - n_ozs_n
    F_ohl = F_o * p["F_ohl"]
    n_ohl_1mm = F_ohl / (math.pi * (D_zh_n + D_zh_vn) * p["h_s_max"])  # 8.6.7 при щели h_s_max
    n_ohl = min(max(math.ceil(n_ohl_1mm), p["n_ohl_min"]), 7)
    h_s = F_ohl / (n_ohl * math.pi * (D_zh_n + D_zh_vn))
    F_ohl1 = math.pi * (D_zh_n + D_zh_vn) * h_s
    r.update(q=q, W_gz=W_gz, d_eff=d_eff, d_ozg=d_ozg, n_ozg=n_ozg, t_o=t_o, n_ozg_n=n_ozg_n, n_ozg_vn=n_ozg_vn,
             d_ozs=d_ozs, n_ozs=n_ozs, t_ozs=t_ozs, n_ozs_n=n_ozs_n, n_ozs_vn=n_ozs_vn, F_ohl1=F_ohl1, n_ohl=n_ohl,
             n_ohl_1mm=n_ohl_1mm, h_s=h_s)

    # ---------- 8.7. Головная часть ЖТ ----------
    F_fr = F_o * p["F_fr"]
    n_forc = round(math.pi * D_sr / (p["t_fr"] * H_zh))  # 8.7.4 (число завихрителей = числу форсунок)
    F_z = 0.8 * F_fr / n_forc  # 8.7.1
    cphi = math.cos(math.radians(p["phi_z"]))
    R_nz = p["R_vnz"] * 1.5
    for _ in range(100):  # 8.7.2 (точная формула, R_нз входит в обе части)
        R_new = math.sqrt((F_z + p["delta_z"] * p["n_z_bl"] * (R_nz - p["R_vnz"])) / (math.pi * cphi)
                          + p["R_vnz"] ** 2)
        if abs(R_new - R_nz) < 1e-10:
            break
        R_nz = R_new
    beta_cone = 2 * p["phi_z"] - 10  # 8.7.3
    r.update(F_fr=F_fr, n_forc=n_forc, F_z=F_z, R_nz=R_nz, beta_cone=beta_cone)

    # ---------- 8.8. Характеристики КС ----------
    V_zht = math.pi * D_sr * H_zh * L_zht  # объём ЖТ
    k_v = 1.735e6 * G_k * (1 - p["G_ohl"]) / (P_k ** 1.25 * T_k * V_zht)  # 8.8.1 (P в Па)
    eta = 1 - 0.3 * k_v  # кольцевая КС
    alpha_sr = 1 / k_v ** 0.7  # 8.8.2 (k_ср ≈ k_v)
    alpha_zg = p["F_fr"] * alpha  # коэффициент избытка воздуха в зоне горения
    if alpha_zg > 1:
        eta_zg = 0.85  # 0,8…0,9 в зоне горения
        T_zg = T_k + p["H_u"] * eta_zg / (c_pg * (1 + alpha_zg * L_o))
    else:
        eta_zg = alpha_zg  # в богатой области полнота лимитируется остаточным воздухом
        T_zg = T_k + p["H_u"] * eta_zg / (c_pg * (L_o + 1 / alpha_zg))
    L_zg = L_pz + max(L_zd, 0.0)
    W_zg_hot = W_zg * T_zg / T_k
    tau_pr = L_zg / W_zg_hot
    NOx = 3.84e14 * (1.1 / alpha) ** 1.7 * math.exp(-65000 / T_zg) * math.sqrt(P_k / T_zg) * tau_pr  # %об.
    EI_CO = (1 - eta) * 1e3 / (0.232 + 1 / p["beta_NOx"])  # 8.8.4: EI_CH = EI_CO/β
    r.update(V_zht=V_zht, k_v=k_v, eta=eta, alpha_sr=alpha_sr, alpha_zg=alpha_zg, eta_zg=eta_zg, T_zg=T_zg,
             L_zg=L_zg, tau_pr=tau_pr, NOx=NOx, EI_CO=EI_CO, EI_CH=EI_CO / p["beta_NOx"])

    r["geo"] = layout(r, diff)
    r["warnings"] = _checks(r)
    return r


def layout(r, diff):
    """
    Меридиональный контур КС, м. Ось x — назад (от компрессора к турбине), x = 0 — выход осевого ЛД ЦБК.
      1) диффузор КС (п. 8.3): от выхода ЛД (D_к.вн/D_к.н) до D_вн1/D_н1 на длине L_д, далее внезапное
         расширение до D_2вн/D_2н; D_2н — корпус КС, D_2вн — наружная стенка ЖТ;
      2) газосборник стоит вплотную (GAP_WALL) за задней стенкой радиального диффузора ЦБК; он образован
         двумя полуокружностями: наружная стенка соединяет D_ж.н с втулкой СА, внутренняя — D_ж.вн с корпусом
         СА (как R52,5 и R17 на рис. 8.3); обе заканчиваются в плоскости входа в СА ТВД;
      3) ЖТ: прямой участок L_п.з + L_з.д (смеситель L_см — это поворот, п. 8.10), купол-полуокружность,
         за ним зазор Δl до заднего торца корпуса (торцы форсунок);
      4) внутренний корпус КС — на диаметре корпуса СА D_т.н.
    """
    R = lambda D: D / 2
    r_zh_n, r_zh_vn = R(r["D_zh_n"]), R(r["D_zh_vn"])
    r_t_n, r_t_vn = R(r["D_t_n"]), R(r["D_t_vn"])
    x_back, hub = diffuser_hub(diff)
    rc_o, Ro = (r_zh_n + r_t_vn) / 2, (r_zh_n - r_t_vn) / 2
    rc_i, Ri = (r_zh_vn + r_t_n) / 2, (r_zh_vn - r_t_n) / 2
    x_nose = x_back + GAP_WALL
    x_c = x_nose + Ro
    L_straight = r["L_pz"] + max(r["L_zd"], 0.0)
    x_dome = x_c + L_straight
    # Задняя стенка корпуса скошена под 45° (как на чертеже books/гг.png) и опирается на наружную стенку
    # переходного канала ТВД → СТ: линия x + r = C_wall, отстоящая от купола на Δl (п. 8.3.9)
    x_end = x_dome + (r["H_zh"] / 2 + r["dl"]) * math.sqrt(2)  # стенка на среднем радиусе ЖТ
    C_wall = x_end + r["D_sr"] / 2

    # Наименьший радиальный зазор между стенкой диффузора ЦБК (колено, ЛД, диффузор КС) и наружной стенкой
    # газосборника / ЖТ
    wall = hub + [(0.0, R(r["D_k_vn"])), (r["L_d"], R(r["D1_vn"]))]
    clear = math.inf
    for (xa, ra), (xb, rb) in zip(wall, wall[1:]):
        for s in (0.0, 0.5, 1.0):
            x, rw = xa + (xb - xa) * s, ra + (rb - ra) * s
            if x >= x_c:
                r_out = r_zh_n
            elif x > x_c - Ro:
                r_out = rc_o + math.sqrt(Ro ** 2 - (x - x_c) ** 2)
            else:
                continue
            clear = min(clear, rw - r_out)

    return dict(r_k_vn=R(r["D_k_vn"]), r_k_n=R(r["D_k_n"]), r_d1_vn=R(r["D1_vn"]), r_d1_n=R(r["D1_n"]),
                r_2vn=R(r["D2_vn"]), x_d1=r["L_d"], x_back=x_back, hub=hub, r3=diff["r3"], x_nose=x_nose,
                rc_o=rc_o, Ro=Ro, rc_i=rc_i, Ri=Ri, x_c=x_c, x_dome=x_dome, x_end=x_end, C_wall=C_wall, x_top=C_wall - R(r["D_n"]),
                L_under=C_wall - r_t_n - x_c,
                L_turn=math.pi * ((r["D_sr"] - r["D_t_sr"]) / 4), clear=clear,
                r_vyh_vn=r_t_vn, r_vyh_n=r_t_n, r_zh_vn=r_zh_vn, r_zh_n=r_zh_n, r_ksn=R(r["D_n"]))


def _rng(w, name, val, key, fmt="{:.1f}", unit="", why=""):
    lo, hi = RECOMMEND[key]
    if not lo <= val <= hi:
        w.append(f"{name} = {fmt.format(val)}{unit} вне рекомендуемых {lo}…{hi}{unit}" + (f" — {why}" if why else ""))


def _checks(r):
    w, p, g = [], r["params"], r["geo"]
    _rng(w, "W_к", r["W_k"], "W_k", unit=" м/с", why="скорость на выходе ЦБК (п. 8.2.1)")
    _rng(w, "W_г", r["W_g"], "W_g", unit=" м/с",
         why="вход в СА ТВД (п. 8.2.5): короче лопатки СА турбина не проходит свои проверки прочности и "
             "раскрытия канала (см. отчёт)")
    size = "КС велика по площади для данного расхода (п. 8.10: H_к = (D_н − D_т)/2)"
    _rng(w, "W_m", r["W_m"], "W_m", unit=" м/с", why=size)
    _rng(w, "W_0", r["W_o"], "W_o", unit=" м/с", why=size)
    _rng(w, "W_с.ж.т", r["W_szht"], "W_szht", unit=" м/с", why=size)
    _rng(w, "W_к.к", r["W_kk"], "W_kk", unit=" м/с")
    for key, name in (("F_fr", "F̄фр"), ("F_ozg", "F̄озг"), ("F_ozs", "F̄озс"), ("F_ohl", "F̄охл")):
        _rng(w, name, p[key], key, fmt="{:.2f}", why="сумма долей = 1 при рекомендуемых диапазонах недостижима")
    if abs(p["F_fr"] + p["F_ozg"] + p["F_ozs"] + p["F_ohl"] - 1) > 1e-6:
        w.append("Сумма относительных площадей отверстий ≠ 1 (п. 8.5.1)")
    _rng(w, "d_озг", r["d_ozg"], "d_ozg", fmt="{:.4f}", unit=" м")
    if r["t_o"] <= 2 * r["d_ozg"]:
        w.append(f"Шаг отверстий зоны горения t₀ = {r['t_o'] * 1000:.1f} мм ≤ 2d (п. 8.6.4) — уменьшите n_озг")
    _rng(w, "Число поясов охлаждения", r["n_ohl"], "n_ohl", fmt="{:.0f}")
    if r["h_s"] < p["h_s_max"]:
        w.append(f"Щель поясов охлаждения h_s = {r['h_s'] * 1000:.2f} мм меньше рекомендуемых 1…2 мм (п. 8.6.7) — "
                 f"уменьшена, чтобы получить {r['n_ohl']} поясов"
                 + (f"; меньше {p['h_s_min'] * 1000:.1f} мм — технологически трудно" if r["h_s"] < p["h_s_min"] else ""))
    if 2 * r["R_nz"] > 2 * r["H_zh"]:
        w.append("Завихритель не помещается в головную часть ЖТ")
    if r["alpha_sr"] <= r["alpha_zg"]:
        w.append(f"α_ср = {r['alpha_sr']:.2f} ≤ α_з.г = {r['alpha_zg']:.2f} — срыв пламени (п. 8.8.2)")
    if r["L_zd"] < 0:
        w.append("L_з.д < 0: L_ж.т по θ короче суммы первичной зоны и смесителя (п. 8.5.1)")
    if r["D2_vn"] < r["D_zh_n"] - 1e-6:
        w.append(f"ЖТ выше внутренней стенки зоны внезапного расширения ({r['D_zh_n'] * 1000:.1f} > "
                 f"{r['D2_vn'] * 1000:.1f} мм) — поднимите диффузор ЦБК (kamera_sgoraniya/podbor_diffuzor.py)")
    if g["clear"] < CLEAR_MIN:
        w.append(f"Зазор между стенкой диффузора ЦБК и ЖТ/газосборником {g['clear'] * 1000:.1f} мм < "
                 f"{CLEAR_MIN * 1000:.0f} мм")
    return w


